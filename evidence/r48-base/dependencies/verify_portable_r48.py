"""Portable package verifier: relative runtime paths and optional graph exports."""
from pathlib import Path
import argparse,collections,hashlib,json,os,shutil,subprocess
ROOT=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
read=lambda p:json.loads(p.read_text(encoding='utf-8-sig'))
def semantic_graph(g):
 # Paths in provenance legitimately change after relocation. Do not alter
 # any other attribute, identifier, port, parameter, value or connectivity.
 g=json.loads(json.dumps(g))
 for obj in [g,*g.get('cells',{}).values(),*g.get('netnames',{}).values()]:
  obj.get('attributes',{}).pop('src',None)
 # Upstream techmap names autogenerated NOT cells using cells_map.v's full
 # path. Canonicalize only that prefix, retaining parent, line and unique ID.
 cells={}
 for name,cell in g.get('cells',{}).items():
  parent,sep,tail=name.partition('.$not$');marker='share/intel/cycloneiv/cells_map.v:'
  if name.startswith('$techmap')and sep and marker in tail:
   name=parent+sep+'RUNTIME/'+tail[tail.index(marker):]
  assert name not in cells,'Relocation name canonicalization collided'
  cells[name]=cell
 g['cells']=cells
 return g
ap=argparse.ArgumentParser();ap.add_argument('--out',type=Path);ap.add_argument('--check-only',action='store_true');args=ap.parse_args()
manifest=read(ROOT/'SHA256.json')
for name,digest in manifest.items():
 p=ROOT/name;assert p.is_file()and sha(p)==digest,('Package integrity',name)
if args.check_only:
 print('PACKAGE_FILES_PASS',len(manifest));raise SystemExit(0)
assert args.out is not None,'Choose a new output directory outside this package'
out=args.out.resolve();assert not out.exists()and ROOT!=out and ROOT not in out.parents
out.mkdir(parents=True)
fixtures=read(ROOT/'verification/fixtures.json');report={'status':'RUNNING','cases':{},'package_manifest_sha256':sha(ROOT/'SHA256.json'),'program_sha256':sha(ROOT/'yosys.exe')}
env={k:v for k,v in os.environ.items()if not k.startswith('YOSYS')and k not in ['ABC','FPGA_DIAG_FILE']}
env['PATH']=str(ROOT)+os.pathsep+env.get('SystemRoot','C:/Windows')+'/System32'
for name,c in fixtures['cases'].items():
 W=out/name;W.mkdir()
 for n,h in c['input_sha256'].items():
  p=ROOT/'verification/fixtures'/name/n;assert sha(p)==h;shutil.copy2(p,W/n)
 (W/'run.ys').write_text(c['script'],encoding='utf-8')
 with(W/'run.log').open('wb')as log:subprocess.run([str(ROOT/'yosys.exe'),'-Q','-s','run.ys'],cwd=W,env=env,stdout=log,stderr=subprocess.STDOUT,check=True,timeout=120)
 text=(W/'run.log').read_text(encoding='utf-8',errors='replace');assert 'ABC: Error:'not in text and 'ABC: ERROR:'not in text
 for cp in ['checkpoint','final']:
  g=read(W/(cp+'.json'))['modules'][c['top']]
  assert semantic_graph(g)==semantic_graph(read(ROOT/'verification/expected'/name/(cp+'.json'))['modules'][c['top']]),('Relocation graph differs',name,cp)
 cells=read(W/'final.json')['modules'][c['top']]['cells'];h=collections.Counter(c['type']for c in cells.values())
 row={'status':'PASS','logic':h['cycloneiv_lcell_comb']+h['$not'],'dff':h['dffeas'],'checkpoint_and_final_graph_identity_excluding_src_paths':True}
 assert row['logic']==c['logic']and row['dff']==c['dff']
 report['cases'][name]=row;(out/'summary.json').write_text(json.dumps(report,indent=2),encoding='utf-8');print(name,'PASS',row['logic'],flush=True)
report['status']='PASS';(out/'summary.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
print('PORTABLE_TEN_CASE_GRAPH_REPRODUCTION_PASS')
